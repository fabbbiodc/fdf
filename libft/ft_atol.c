#include "libft.h"

long	ft_atol(const char *str)
{
	long	rslt;
	int		sign;

	rslt = 0;
	sign = 1;
	while (ft_isspace(*str))
		str++;
	if (*str == '-' || *str == '+')
	{
		if (*str == '-')
			sign = -1;
		str++;
	}
	while (ft_isdigit(*str))
	{
		rslt = rslt * 10 + (*str - '0');
		str++;
	}
	return (rslt * sign);
}
